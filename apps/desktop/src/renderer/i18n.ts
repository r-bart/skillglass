function translateTo(value: string, locale: Locale): string {
  const exact = (locale === "en" ? ES_TO_EN : EN_TO_ES).get(value)
  if (exact !== undefined) return exact

  for (const pattern of PATTERNS) {
    const match = value.match(locale === "en" ? pattern.es : pattern.en)
    if (match !== null) {
      const groups = match.slice(1)
      return locale === "en" ? pattern.toEnglish(...groups) : pattern.toSpanish(...groups)
    }
  }

  if (value.includes(" · ")) {
    const translatedParts = value.split(" · ").map((part) => translateTo(part, locale))
    const translated = translatedParts.join(" · ")
    if (translated !== value) return translated
  }
  return value
}

export function localize(value: string, locale = activeLocale): string {
  return translateTo(value, locale)
}

export function getActiveLocale(): Locale {
  return activeLocale
}

export function setActiveLocale(locale: Locale): void {
  activeLocale = locale
}

export function loadSavedLocale(): Locale {
  if (typeof window === "undefined") return DEFAULT_LOCALE
  try {
    const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY)
    return saved === "en" || saved === "es" ? saved : DEFAULT_LOCALE
  } catch {
    return DEFAULT_LOCALE
  }
}

export function saveLocale(locale: Locale): void {
  activeLocale = locale
  if (typeof document !== "undefined") document.documentElement.lang = locale
  if (typeof window === "undefined") return
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale)
  } catch {
    // A blocked storage API should not prevent the language from changing.
  }
}

const LOCALIZED_ATTRIBUTES = new Set([
  "aria-description",
  "aria-label",
  "alt",
  "placeholder",
  "title",
])

function localizeNode(node: ReactNode): ReactNode {
  if (typeof node === "string") return localize(node)
  if (Array.isArray(node)) return node.map(localizeNode)
  return node
}

function localizeProps(props: unknown): unknown {
  if (props === null || typeof props !== "object") return props
  const source = props as Record<string, unknown>
  let changed = false
  const next = { ...source }
  for (const attribute of LOCALIZED_ATTRIBUTES) {
    const value = source[attribute]
    if (typeof value !== "string") continue
    const translated = localize(value)
    if (translated === value) continue
    next[attribute] = translated
    changed = true
  }
  return changed ? next : props
}

export const createElement: typeof reactCreateElement = ((
  type: Parameters<typeof reactCreateElement>[0],
  props: Parameters<typeof reactCreateElement>[1],
  ...children: ReactNode[]
) => reactCreateElement(
  type,
  localizeProps(props) as Parameters<typeof reactCreateElement>[1],
  ...children.map(localizeNode),
)) as typeof reactCreateElement
